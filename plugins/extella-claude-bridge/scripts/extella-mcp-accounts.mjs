// ── PER-ACCOUNT EXTELLA MCP CONNECTIONS ────────────────────────────────────
// Direction A (Claude Code → Extella). One Extella account is one MCP server
// entry with its own environment variable. This module derives names only; it
// performs no writes and touches no live configuration.
//
// Why not plugin userConfig: a plugin carries exactly one set of userConfig
// values, so a second account would overwrite the first. That makes it the
// wrong primary store for a rule that says "each account is its own
// connection". userConfig stays available for a single-account convenience
// path, but it is not the contract below.

import { createHash } from "node:crypto";

const ACCOUNT_HANDLE = /^acct_[a-f0-9]{12}$/;
const SERVER_NAME = /^extella_acct_[a-f0-9]{12}$/;
const ENVIRONMENT_NAME = /^EXTELLA_MCP_TOKEN_ACCT_[A-F0-9]{12}$/;

const EXTELLA_MCP_URL = "https://api.extella.ai/mcp/";

// A stable, non-reversible handle. Twelve hex characters of a domain-separated
// digest: enough to keep two accounts apart on one machine, short enough to
// read in a config file, and useless to anyone who obtains it.
function accountHandle(token) {
  if (typeof token !== "string" || token.trim().length < 8) {
    throw new Error("An Extella account token is required to derive a handle");
  }
  const digest = createHash("sha256")
    .update(`extella-mcp-account-v1.${token.trim()}`, "utf8")
    .digest("hex");
  return `acct_${digest.slice(0, 12)}`;
}

function serverName(handle) {
  if (!ACCOUNT_HANDLE.test(handle || "")) {
    throw new Error("A valid Extella account handle is required");
  }
  return `extella_${handle}`;
}

function environmentName(handle) {
  if (!ACCOUNT_HANDLE.test(handle || "")) {
    throw new Error("A valid Extella account handle is required");
  }
  return `EXTELLA_MCP_TOKEN_${handle.toUpperCase()}`;
}

// Extella needs three headers, not one. Measured 2026-08-14: a connection
// carrying only X-Auth-Token fails every tool call with a dependency
// resolution error for "token". The canon already said so —
// deploy-extella-assets.mjs sends the same trio on every REST call.
//
// X-Agent-Id is a property of the token, not a constant. The literal
// "agent_extella_default" fails; POST /api/token/validate returns the agent id
// that belongs to this token, and it is resolved once at setup.
const EXTELLA_PROFILE_ID = "default";

// headersHelper rather than `${VAR}`. Both keep the token out of the config
// file and out of git, but the variable form also puts it in the process
// environment and, worse, `claude mcp get` prints the resolved value in plain
// text. With a helper there is nothing for that command to print: the measured
// output shows no Headers block at all. The token stays in a 0600 file and
// reaches the request without passing through argv or the environment.
function mcpServerEntry(handle, { headersHelperPath }) {
  if (typeof headersHelperPath !== "string" || !headersHelperPath.startsWith("/")) {
    throw new Error("An absolute headersHelper path is required");
  }
  return {
    type: "http",
    url: EXTELLA_MCP_URL,
    headersHelper: headersHelperPath,
  };
}

function tokenFilePath(handle, home) {
  if (!ACCOUNT_HANDLE.test(handle || "")) {
    throw new Error("A valid Extella account handle is required");
  }
  return `${home}/.extella/mcp/${handle}.token`;
}

// The helper reads the token at request time and never receives it as an
// argument, so it appears in no process listing.
function headersHelperScript(handle, { agentId, home }) {
  if (!/^agent_[A-Za-z0-9_-]{8,128}$/.test(agentId || "")) {
    throw new Error("A resolved Extella agent id is required");
  }
  return [
    "#!/bin/sh",
    "# Generated by the Extella Claude bridge. Reads a 0600 token file.",
    `printf '{"X-Auth-Token":"%s","X-Profile-Id":"${EXTELLA_PROFILE_ID}","X-Agent-Id":"${agentId}"}\\n' \\`,
    `  "$(cat "${tokenFilePath(handle, home)}")"`,
    "",
  ].join("\n");
}

function mcpConfigFragment(handle, options) {
  return { mcpServers: { [serverName(handle)]: mcpServerEntry(handle, options) } };
}

// `claude mcp list` and `claude mcp get` report "✓ Connected" for a server
// with no token at all, and for a deliberately wrong one. Measured: an MCP
// `initialize` returns an identical HTTP 200 in all three cases, so the health
// check proves reachability and nothing else.
//
// Account binding is therefore verified against this endpoint, which is what
// the Codex installer already uses, and which also yields the agent id the
// headers need. It calls no model.
const TOKEN_VALIDATE_URL = "https://api.extella.ai/api/token/validate";

function isProvenAccountBinding(validateResponse) {
  return (
    validateResponse?.valid === true &&
    /^agent_[A-Za-z0-9_-]{8,128}$/.test(validateResponse?.agent_id || "")
  );
}

// Adding a second account must not disturb the first. Merge is by server name,
// which is derived from the account, so two accounts can never contend for one
// entry and a repeated setup for the same account is idempotent.
function mergeAccountConfig(existing, handle, options) {
  const base =
    existing && typeof existing === "object" && !Array.isArray(existing)
      ? existing
      : {};
  const servers =
    base.mcpServers && typeof base.mcpServers === "object" ? base.mcpServers : {};
  return {
    ...base,
    mcpServers: {
      ...servers,
      [serverName(handle)]: mcpServerEntry(handle, options),
    },
  };
}

// Serialized form must never contain a token. Tests assert this against a
// known token value rather than trusting the shape by inspection.
function containsTokenMaterial(serialized, token) {
  return typeof token === "string" && token.length >= 8
    ? String(serialized).includes(token)
    : false;
}

export {
  ACCOUNT_HANDLE,
  ENVIRONMENT_NAME,
  EXTELLA_MCP_URL,
  EXTELLA_PROFILE_ID,
  SERVER_NAME,
  TOKEN_VALIDATE_URL,
  accountHandle,
  containsTokenMaterial,
  environmentName,
  headersHelperScript,
  isProvenAccountBinding,
  mcpConfigFragment,
  mcpServerEntry,
  mergeAccountConfig,
  serverName,
  tokenFilePath,
};
